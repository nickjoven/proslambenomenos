#!/usr/bin/env python3
"""P-15 derivation layer (pre-registration): the spectral-dimension
instrument's exact anchors. Spectral dimension is defined here as

    d_s(t) = -2 d ln P(t) / d ln t,
    P(t)   = (1/n) Tr exp(-t L)  =  (1/n) sum_k exp(-lambda_k t),

the mean return probability of the continuous-time random walk
generated by the graph Laplacian L. Everything in this file is exact:
P and its t-derivative are analytic sums over closed-form spectra, so
d_s(t) = 2t * (sum lambda e^{-lambda t}) / (sum e^{-lambda t}) is
computed with NO fitting anywhere. Fitting enters the instrument only
for Monte Carlo objects, and never in this file.

Anchors (each an EQ line):
  EQ1  cycle C_n spectrum: lambda_k = 2(1 - cos(2 pi k/n)) - checked
       against the explicitly built Laplacian at n = 12 (residual of
       L v_k = lambda_k v_k for the cosine eigenvectors).
  EQ2  the line: for t << t_mix the C_4096 curve reproduces the exact
       Z curve d_s(t) = 2t(2 - 2 I1(2t)/I0(2t)) (Bessel ratio via its
       continued fraction, stdlib); pinned values at t = 5..60.
  EQ3  d_s(t) -> 1 from ABOVE with the derived 1/(4t) correction:
       d_s(t) = 1 + 1/(8t) + O(1/t^2)... the coefficient is measured
       from the exact curve and pinned, not assumed.
  EQ4  products add: P_{C_n x C_n}(t) = P_{C_n}(t)^2, so d_s adds;
       checked exactly via the 2D eigen-sum at n = 64.
  EQ5  the finite-size window: for t > t_mix = 1/lambda_1 every
       finite graph's d_s(t) decays to 0 (P plateaus at 1/n); the
       instrument must never report outside [t_lat, c/lambda_1].
       Checked on K_n (complete graph) where the decay is closed
       form, and the window bound pinned as a rule.
  EQ6  dense circulant short-time limit: as t -> 0, d_s(t) -> 2 t
       * mean(lambda) -> 0 on ANY finite graph (all walks return);
       the short end of the window is where d_s peaks, and for
       C_4096({1..6}) the crossover profile is pinned for the
       registered computation to reproduce with an independent
       implementation.
Pinned outputs -> p15_registration.json.
"""
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT, FAILED = [], []


def eq(n, ok, statement, detail):
    line = f"EQ {n} {'PASS' if ok else 'FAIL'}  {statement}  | {detail}"
    OUT.append(line)
    print(line)
    if not ok:
        FAILED.append(n)


def cycle_spectrum(n, S=(1,)):
    """Circulant Laplacian eigenvalues for symmetric offsets S."""
    return [sum(2 * (1 - math.cos(2 * math.pi * k * s / n)) for s in S)
            for k in range(n)]


def ds_exact(spec, t):
    """d_s(t) = 2t <lambda>_P from the exact eigen-sum (no fitting)."""
    mx = min(l * t for l in spec)
    num = sum(l * math.exp(-(l * t - mx)) for l in spec)
    den = sum(math.exp(-(l * t - mx)) for l in spec)
    return 2 * t * num / den


def bessel_ratio(x, depth=80):
    """I1(x)/I0(x) by the continued fraction
    I1/I0 = (x/2) / (1 + (x^2/4)/(2 + (x^2/4)/(3 + ...))):
    the tail q_2 is built from the bottom up, stopping at k = 2."""
    q = 0.0
    for k in range(depth, 1, -1):
        q = (x * x / 4) / (k + q)
    return (x / 2) / (1 + q)


def main():
    # EQ1: cycle spectrum against the explicit Laplacian
    n1 = 12
    spec = cycle_spectrum(n1)
    worst = 0.0
    for k in range(n1):
        v = [math.cos(2 * math.pi * k * j / n1) for j in range(n1)]
        for j in range(n1):
            lv = 2 * v[j] - v[(j - 1) % n1] - v[(j + 1) % n1]
            worst = max(worst, abs(lv - spec[k] * v[j]))
    eq(1, worst < 1e-12, "C_n Laplacian spectrum lambda_k = 2(1 - cos(2 pi k/n))",
       f"worst eigen-residual {worst:.2e} at n = {n1}")

    # EQ2: C_4096 vs the exact Z curve (Bessel continued fraction)
    n2 = 4096
    spec2 = cycle_spectrum(n2)
    t_pins = [5.0, 10.0, 20.0, 40.0, 60.0]
    rows, worst2 = [], 0.0
    ds_pins = {}
    for t in t_pins:
        ds_c = ds_exact(spec2, t)
        r = bessel_ratio(2 * t)
        ds_z = 2 * t * (2 - 2 * r)
        worst2 = max(worst2, abs(ds_c - ds_z))
        ds_pins[str(t)] = ds_c
        rows.append(f"t={t:g}: {ds_c:.10f} (Z: {ds_z:.10f})")
    eq(2, worst2 < 1e-9, "C_4096 d_s(t) = exact Z curve 2t(2 - 2 I1/I0) for t << t_mix",
       "; ".join(rows[:3]) + f"; worst dev {worst2:.2e}")

    # EQ3: approach 1 from above; measure the 1/t coefficient
    c_est = [(ds_exact(spec2, t) - 1.0) * t for t in (30.0, 60.0, 120.0)]
    drift = abs(c_est[2] - c_est[1]) / abs(c_est[1])
    eq(3, all(x > 0 for x in c_est) and drift < 0.05,
       "d_s(t) = 1 + c/t + ..., c measured from the exact curve",
       f"c(t=30,60,120) = {c_est[0]:.6f}, {c_est[1]:.6f}, {c_est[2]:.6f} (drift {drift:.2%})")

    # EQ4: products add
    n4 = 64
    s1 = cycle_spectrum(n4)
    p1 = lambda t: sum(math.exp(-l * t) for l in s1) / n4          # noqa: E731
    s2 = [a + b for a in s1 for b in s1]
    p2 = lambda t: sum(math.exp(-l * t) for l in s2) / (n4 * n4)   # noqa: E731
    worst4 = max(abs(p2(t) - p1(t) ** 2) / p1(t) ** 2 for t in (0.5, 2.0, 8.0))
    ds2 = ds_exact(s2, 8.0)
    eq(4, worst4 < 1e-12 and abs(ds2 - 2 * ds_exact(s1, 8.0)) < 1e-9,
       "P_{CxC} = P_C^2, so d_s adds (torus d_s = 2 x cycle d_s)",
       f"worst product dev {worst4:.2e}; d_s torus(t=8) = {ds2:.6f}")

    # EQ5: the window rule from the spectral gap; K_n closed form
    nk = 50
    speck = [0.0] + [float(nk)] * (nk - 1)
    ds_late = ds_exact(speck, 5.0)               # deep past K_n's 1/lambda_1
    lam1 = cycle_spectrum(n2)[1]
    t_mix = 1.0 / lam1
    ds_past = ds_exact(spec2, 3 * t_mix)
    # past t_mix only the k = +-1 modes survive: the exact two-mode
    # closed form is d_s = 2 t lam1 * 2 e^{-lam1 t} / (1 + 2 e^{-lam1 t})
    two_mode = 12 * math.exp(-3) / (1 + 2 * math.exp(-3))
    eq(5, ds_late < 0.05 and abs(ds_past - two_mode) < 1e-3,
       "past t_mix = 1/lambda_1 d_s decays on the exact two-mode curve; window rule pinned",
       f"K_{nk} d_s(t=5) = {ds_late:.2e}; C_4096 d_s(3 t_mix) = {ds_past:.6f} "
       f"vs two-mode closed form {two_mode:.6f}")

    # EQ6: dense circulant crossover profile, pinned for the instrument
    S6 = tuple(range(1, 7))
    spec6 = cycle_spectrum(n2, S6)
    cross_pins = {}
    for t in (0.05, 0.2, 1.0, 5.0, 20.0, 80.0):
        cross_pins[str(t)] = ds_exact(spec6, t)
    peak_t = max(cross_pins, key=lambda k: cross_pins[k])
    eq(6, cross_pins["80.0"] < 1.6 and max(cross_pins.values()) > 1.0,
       "C_4096({1..6}): short-sigma peak then crossover toward the 1D plateau",
       "; ".join(f"t={k}: {v:.4f}" for k, v in cross_pins.items()))

    pin = {"definition": "d_s(t) = 2t <lambda>_P, P = mean Tr exp(-tL), exact log-derivative",
           "cycle_n": n2, "ds_line_pins": ds_pins,
           "one_over_t_coeff": c_est[2],
           "window_rule": {"t_mix_is": "1/lambda_1", "report_only_below": 0.5,
                           "meaning": "report d_s only for t < 0.5/lambda_1"},
           "dense_circulant": {"S": list(S6), "crossover_pins": cross_pins,
                               "peak_t": float(peak_t)},
           "chain_identity_tol": 1e-6,
           "tolerances": {"anchor_abs": 1e-9, "reimpl_abs": 1e-10}}
    (HERE / "p15_registration.json").write_text(json.dumps(pin, indent=1) + "\n")
    (HERE / "p15_derive_out.txt").write_text("\n".join(OUT) + "\n")
    print(f"\npinned: line d_s at 5 t-values, 1/t coeff {c_est[2]:.6f}, "
          f"dense-circulant crossover at 6 t-values")
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
